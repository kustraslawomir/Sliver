abstract class GenerateDesignTokens : DefaultTask() {
    @get:InputFile @get:PathSensitive(PathSensitivity.NONE)
    abstract val tokens: RegularFileProperty
    @get:OutputDirectory
    abstract val outDir: DirectoryProperty

    private fun argb(hex: String): String {
        val h = hex.removePrefix("#").uppercase()
        require(Regex("[0-9A-F]{6}([0-9A-F]{2})?").matches(h)) { "bad colour $hex" }
        return if (h.length == 6) "0xFF$h" else "0x${h.substring(6)}${h.substring(0, 6)}"
    }

    @TaskAction
    fun generate() {
        @Suppress("UNCHECKED_CAST")
        fun obj(v: Any?) = v as Map<String, Any?>
        val root = obj(groovy.json.JsonSlurper().parse(tokens.get().asFile))
        val c = obj(root["color"]); val l = obj(root["themeLight"]); val a = obj(root["accent"])
        val aDark = obj(a["dark"]); val aLight = obj(a["light"])
        fun s(m: Map<String, Any?>, k: String) = m[k] as? String ?: error("tokens.json: missing $k")
        fun withAlpha(hex: String, aa: String) = "#" + hex.removePrefix("#").take(6) + aa

        fun palette(name: String, f: Map<String, String>) = buildString {
            appendLine("    val $name = TokenPalette(")
            f.forEach { (k, v) -> appendLine("        $k = Color(${argb(v)}),") }
            appendLine("    )")
        }
        val dark = linkedMapOf(
            "bgVoid" to s(c, "bgVoid"), "bgBase" to s(c, "bgBase"), "surface1" to s(c, "surface1"),
            "surface2" to s(c, "surface2"), "surface3" to s(c, "surface3"),
            "lineHairline" to s(c, "lineHairline"), "lineStrong" to s(c, "lineStrong"),
            "textPrimary" to s(c, "textPrimary"), "textSecondary" to s(c, "textSecondary"),
            "textTertiary" to s(c, "textTertiary"), "textDisabled" to s(c, "textDisabled"),
            "accent" to s(aDark, "primaryFill"), "onAccent" to s(aDark, "onPrimary"),
            "accentLine" to withAlpha(s(aDark, "primaryFill"), "55"),
            "accentTint" to withAlpha(s(aDark, "primaryFill"), "1F"),
            "onInverse" to s(c, "bgBase"),
            "success" to s(c, "success"), "warning" to s(c, "warning"), "error" to s(c, "error"),
        )
        val light = linkedMapOf(
            "bgVoid" to s(c, "bgVoid"), "bgBase" to s(l, "bg"), "surface1" to s(l, "surface"),
            "surface2" to s(l, "surface2"), "surface3" to s(l, "line"),
            "lineHairline" to s(l, "line"), "lineStrong" to s(l, "lineStrong"),
            "textPrimary" to s(l, "text"), "textSecondary" to s(l, "text2"),
            "textTertiary" to s(l, "muted"), "textDisabled" to s(l, "faint"),
            "accent" to s(aLight, "primaryFill"), "onAccent" to s(aLight, "onPrimary"),
            "accentLine" to withAlpha(s(aLight, "primaryFill"), "55"),
            "accentTint" to withAlpha(s(aLight, "primaryFill"), "14"),
            "onInverse" to s(c, "textPrimary"),
            "success" to s(l, "success"), "warning" to s(l, "warning"), "error" to s(l, "danger"),
        )
        val type = obj(root["type"]).filterKeys { !it.startsWith("mono") }
        val space = (root["space"] as List<*>)
        val radius = obj(root["radius"])
        fun num(v: Any?) = (v as Number).toString().removeSuffix(".0")

        val out = buildString {
            appendLine("// GENERATED by :composeApp:generateDesignTokens from design/tokens.json. Do not edit.")
            appendLine("package app.sliver.core.theme.generated")
            appendLine()
            appendLine("import androidx.compose.ui.graphics.Color")
            appendLine()
            appendLine("class TokenPalette(")
            dark.keys.forEach { appendLine("    val $it: Color,") }
            appendLine(")")
            appendLine()
            appendLine("class TokenText(val size: Int, val line: Int, val weight: Int, val tracking: Float)")
            appendLine()
            appendLine("object Tokens {")
            appendLine("    const val AppName = \"${s(root, "appName")}\"")
            append(palette("DarkColors", dark))
            append(palette("LightColors", light))
            appendLine("    val RecordRed = Color(${argb(s(a, "record"))})")
            appendLine("    val Scrim = Color(${argb(s(c, "scrim"))})")
            appendLine()
            type.forEach { (k, v) ->
                val m = obj(v)
                val name = k.replaceFirstChar { it.uppercase() }
                appendLine("    val $name = TokenText(${num(m["size"])}, ${num(m["line"])}, ${num(m["weight"])}, ${num(m["tracking"] ?: 0)}f)")
            }
            appendLine()
            space.forEachIndexed { i, v -> appendLine("    const val Space${i + 1} = ${num(v)}") }
            appendLine()
            radius.forEach { (k, v) -> appendLine("    const val Radius${k.replaceFirstChar { it.uppercase() }} = ${num(v)}") }
            appendLine("}")
        }
        val f = outDir.get().file("app/sliver/core/theme/generated/Tokens.kt").asFile
        f.parentFile.mkdirs()
        f.writeText(out)
    }
}

